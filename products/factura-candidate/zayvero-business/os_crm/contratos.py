"""LOTE 6 — Contratos: persistencia PostgreSQL para CRM/Ventas."""
from __future__ import annotations

from typing import Protocol, runtime_checkable


@runtime_checkable
class RepositorioCRM(Protocol):
    """La implementará el adaptador PostgreSQL del issue #1."""

    def guardar_cliente(self, cliente) -> None: ...
    def obtener_cliente(self, cliente_id: str): ...
    def guardar_venta(self, venta: dict) -> None: ...
    def listar_ventas(self, company_id: str) -> list: ...
    def guardar_promesa(self, cuenta_id: str, promesa: dict) -> None: ...
